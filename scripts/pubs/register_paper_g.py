#!/usr/bin/env python3
"""Register every number printed in Paper G.

Paper G is rendered by docs/reports/paper_g/scripts/build_paper_g.py: each placeholder
<<alias:key:column:format>> of paper_g_draft.md, and of the tables the build generates, is
filled from a committed result file under outputs/analysis/paper_g/. This script reads the same
placeholders, through the functions of that build, and writes the generated Paper G block of
pub/claim_registry.toml:

1. One claim per printed number with decimals (and per thousands-separated integer) of the
   rendered manuscript docs/reports/paper_g/paper_g.md, re-derived by the `paper_g` resolver of
   claim_sources.py (RCA-001). Bare integers (counts of blocks, small counts) are outside the
   registry, as for every manuscript; --check covers them, because it fails unless paper_g.md
   is exactly what the build renders from the result files.
2. Exclusivity exceptions for paper_g.md where one of its own registered values, or a
   structural constant, equals a result of an unpublished manuscript at the printed precision.
   A literal that neither accounts for stops the script.

    python docs/reports/paper_g/scripts/build_paper_g.py     # lane paper-g
    python scripts/pubs/register_paper_g.py [--check]        # shared files
"""
from __future__ import annotations

import argparse
import importlib.util
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from register_paper_f import _collisions as _collisions_f  # noqa: E402
import register_paper_f  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
G = ROOT / "docs" / "reports" / "paper_g"
REGISTRY = ROOT / "pub" / "claim_registry.toml"
MANUSCRIPT = "docs/reports/paper_g/paper_g.md"
FILES = (MANUSCRIPT,)
BEGIN = "# >>> paper_g generated by scripts/pubs/register_paper_g.py -- do not edit >>>"
END = "# <<< paper_g generated <<<"
AFTER = "# >>> paper_f generated by scripts/pubs/register_paper_f.py"


def _build_module():
    spec = importlib.util.spec_from_file_location("build_paper_g",
                                                  G / "scripts" / "build_paper_g.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _literal(bpg, v: float, f: str) -> tuple[str | None, int, bool]:
    """Printed literal as the scanner sees it (None for a bare integer), decimals, x100."""
    if f == "d":
        return None, 0, False
    if f == "int":
        s = bpg.fmt(v, "int")
        return (s if "," in s else None), 0, False
    if f == "p":
        f = "f5" if v < 0.001 else "f3"
    if f in ("pct0", "pct1"):
        s = bpg.fmt(v, f)
        return (s if "." in s else None), int(f[3]), True
    s = bpg.fmt(v, f).replace("−", "")
    return (s if "." in s else None), int(f[1]), False


def collect(bpg) -> dict[str, dict]:
    """Claims by id: source, value, tolerance and the printed literal."""
    data = bpg.tables()
    claims: dict[str, dict] = {}
    for alias, key, column, f in bpg.placeholders():
        v = float(data[alias][key][column])
        literal, dec, x100 = _literal(bpg, v, f)
        if literal is None:
            continue
        number = literal.replace(",", "")
        negative = v < 0 and float(number) != 0
        cid = "paper_g." + ".".join([alias, key, column.replace(".", "_"), f])
        claims.setdefault(cid, {
            "source": f"paper_g:{alias}:{key}:{column}" + (":x100" if x100 else ""),
            "value": ("-" if negative else "") + number,
            "tolerance": 0.5 if f == "int" else 0.5 * 10 ** -dec + 1e-9,
            "text": literal})
    return claims


def registry_text(claims: dict[str, dict]) -> str:
    raw = REGISTRY.read_bytes().decode("utf-8")
    eol = "\r\n" if "\r\n" in raw else "\n"
    reg = raw.replace("\r\n", "\n")
    reg = re.sub(r"\n*" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n*", "\n\n", reg,
                 flags=re.DOTALL)
    # The other generated blocks are rewritten in place by their scripts; this block goes
    # before the Paper F block, and each script leaves the others where they are.
    anchor = reg.find(AFTER)
    head = (reg if anchor < 0 else reg[:anchor]).rstrip("\n") + "\n"
    tail = "" if anchor < 0 else "\n" + reg[anchor:].rstrip("\n") + "\n"

    lines = [BEGIN,
             "# Every number with decimals (or a thousands separator) printed in Paper G, its",
             "# tables included, re-derived from outputs/analysis/paper_g/ by the paper_g",
             "# resolver. Regenerated by the script; edit paper_g_draft.md and rebuild instead.", ""]
    for cid, c in sorted(claims.items()):
        lines += ["[[claim]]", f'id = "{cid}"', f'source = "{c["source"]}"',
                  f'value = "{c["value"]}"', f"tolerance = {c['tolerance']:.10g}",
                  f'appears_in = [{{ file = "{MANUSCRIPT}", text = "{c["text"]}" }}]', ""]

    register_paper_f.FILES = FILES  # the collision rule of Paper F, applied to this file
    exceptions, unexplained = _collisions_f(head + "\n" + "\n".join(lines + [END]) + "\n" + tail)
    if unexplained:
        sys.exit("Paper G prints a result of an unpublished manuscript that none of its own "
                 "claims accounts for:\n" + "\n".join(f"- {u}" for u in unexplained))
    if exceptions:
        lines += ["# Chance coincidences: a value of Paper G, or a structural constant, equals a",
                  "# result of an unpublished manuscript at the printed precision.", ""]
    for rel, literal, reason in sorted(exceptions):
        lines += ["[[exclusivity_exception]]", f'file = "{rel}"', f'text = "{literal}"',
                  f'reason = "{reason}"', ""]
    lines.append(END)
    return (head + "\n" + "\n".join(lines) + "\n" + tail).replace("\n", eol)


def _stale(bpg) -> list[str]:
    rendered, problems = bpg.render(bpg.strip_front(bpg.SOURCE.read_text(encoding="utf-8")))
    out = [f"paper_g.md: {p}" for p in problems]
    if (ROOT / MANUSCRIPT).read_text(encoding="utf-8").replace("\r\n", "\n") != rendered:
        out.append(f"{MANUSCRIPT} is not what the build renders from the result files; run "
                   "docs/reports/paper_g/scripts/build_paper_g.py")
    return out


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="Write nothing; fail if paper_g.md or the registry is not what "
                             "the result files and the source give.")
    args = parser.parse_args(argv)
    bpg = _build_module()
    stale = _stale(bpg)
    if stale and not args.check:
        sys.exit("\n".join(stale))
    claims = collect(bpg)
    text = registry_text(claims)
    if REGISTRY.read_bytes().decode("utf-8") != text:
        if args.check:
            stale.append("pub/claim_registry.toml is out of date; run "
                         "scripts/pubs/register_paper_g.py")
        else:
            REGISTRY.write_bytes(text.encode("utf-8"))
    if stale:
        sys.exit("Paper G registration check failed:\n" + "\n".join(f"- {s}" for s in stale))
    print(f"OK: Paper G, {len(claims)} claims")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
