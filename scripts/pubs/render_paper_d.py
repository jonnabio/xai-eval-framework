#!/usr/bin/env python3
"""Render Paper D: paper_d_template.tex -> paper_d.tex, and register every printed number.

Each <<table:key:fmt>> in docs/reports/paper_d/paper_d_template.tex is replaced by the value
of `key` in outputs/analysis/paper_d/<table>.csv (written by paper_d_analysis.py). `key` may
be a difference of two keys (`a-b`). Formats:

    d     integer                       int   integer with thousands separator
    s2..4 signed, 2-4 decimals          u2..4 absolute value, 2-4 decimals
    p     p-value: "<0.001" or 3 decimals

Every rendered number with decimals (and every thousands-separated integer) is written to
the generated block of pub/claim_registry.toml, so scripts/pubs/verify_claims.py
re-derives it from the artifact and confirms it is printed (RCA-001). Nothing in
paper_d.tex is typed by hand; edit the template and re-run.

    python scripts/pubs/render_paper_d.py
"""
from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
D = ROOT / "docs" / "reports" / "paper_d"
SRC = ROOT / "outputs" / "analysis" / "paper_d"
REGISTRY = ROOT / "pub" / "claim_registry.toml"
BEGIN = "# >>> paper_d generated by scripts/pubs/render_paper_d.py -- do not edit >>>"
END = "# <<< paper_d generated <<<"
TOKEN = re.compile(r"<<([a-z0-9_]+):([A-Za-z0-9_.\-]+):([a-z]+\d?)>>")
MANUSCRIPT = "docs/reports/paper_d/paper_d.tex"

# Constants written in the template's prose (not results) that coincide with a B+C value.
PROSE_CONSTANTS = {
    "0.05": "Method constant, not a result: significance level, practical-relevance threshold "
            "and figure bin width stated in the methods",
}

_tables: dict[str, dict[str, float]] = {}


def value(table: str, key: str) -> float:
    if table not in _tables:
        with open(SRC / f"{table}.csv", encoding="utf-8") as fh:
            _tables[table] = {r["metric"]: float(r["value"]) for r in csv.DictReader(fh)}
    t = _tables[table]
    if "-" in key:
        a, b = key.split("-")
        return t[a] - t[b]
    return t[key]


def fmt(v: float, f: str) -> tuple[str, str | None, int]:
    """Return (printed text, registry literal or None, decimals)."""
    if f == "d":
        return str(int(round(v))), None, 0
    if f == "int":
        s = f"{int(round(v)):,}"
        return s, (s if "," in s else None), 0
    if f == "p":
        if v < 0.001:
            return "<0.001", None, 3
        s = f"{v:.3f}"
        return s, s, 3
    dec = int(f[1])
    r = round(v, dec)
    if r == 0:
        r = 0.0
    if f[0] == "s":
        s = f"{r:+.{dec}f}" if r != 0 else f"{0:.{dec}f}"
        return s.replace("-", "−"), f"{abs(r):.{dec}f}", dec   # true minus sign, text mode
    if f[0] == "u":
        s = f"{abs(r):.{dec}f}"
        return s, s, dec
    raise ValueError(f"unknown format {f}")


def collisions(claims: dict) -> dict[str, tuple[str, str]]:
    """Paper D literals that equal, at their printed precision, a protected B+C result."""
    import tomllib
    reg = tomllib.loads(REGISTRY.read_text(encoding="utf-8"))
    cfg = reg.get("exclusivity") or {}
    forbid, allow = tuple(cfg.get("forbid") or []), tuple(cfg.get("allow_if_also") or [])
    protected = []
    for c in reg.get("claim", []):
        files = [s["file"] for s in c.get("appears_in", [])]
        if any(f.startswith(forbid) for f in files) and not any(f.startswith(allow) for f in files):
            protected.append((c["id"], abs(float(c["value"].replace(",", "")))))
    out = {}
    for cid, (_, _, literal, _) in claims.items():
        if "," in literal:
            continue
        dec = len(literal.split(".")[1])
        if dec == 1 and float(literal) < 10:
            continue
        for pid, v in protected:
            if abs(v - float(literal)) <= 0.5 * 10 ** -dec + 1e-12:
                out.setdefault(literal, (cid, pid))
                break
    return out


def main() -> int:
    template = (D / "paper_d_template.tex").read_text(encoding="utf-8")
    claims: dict[str, tuple[str, str, str, float]] = {}

    def sub(m: re.Match) -> str:
        table, key, f = m.groups()
        v = value(table, key)
        text, literal, dec = fmt(v, f)
        if literal is not None and "-" not in key:
            cid = f"paper_d.{table}.{key}.{f}"
            signed = round(v, dec) if f != "int" else round(v)
            tol = 0.5 * 10 ** -dec + 1e-9 if f != "int" else 0.5
            claims[cid] = (f"paper_d:{table}:{key}", f"{signed:.{dec}f}" if f != "int" else str(int(signed)), literal, tol)
        return text

    out = TOKEN.sub(sub, template)
    left = re.findall(r"<<[^>]*>>", out)
    if left:
        sys.exit(f"unresolved placeholders: {left[:5]}")
    header = ("%% GENERATED from paper_d_template.tex by scripts/pubs/render_paper_d.py.\n"
              "%% Do not edit: change the template and re-render.\n")
    (D / "paper_d.tex").write_bytes((header + out).encode("utf-8"))

    lines = [BEGIN,
             "# Every number printed in Paper D, re-derived from outputs/analysis/paper_d/ by the",
             "# paper_d resolver. Regenerated on each render; edit paper_d_template.tex instead.", ""]
    for cid, (source, val, literal, tol) in sorted(claims.items()):
        lines += ["[[claim]]", f'id = "{cid}"', f'source = "{source}"', f'value = "{val}"',
                  f"tolerance = {tol:.10g}",
                  f'appears_in = [{{ file = "{MANUSCRIPT}", text = "{literal}" }}]', ""]
    # Chance coincidences with results of the unpublished Paper B+C: the exclusivity check
    # matches by value at the printed precision, so a short decimal such as 0.025 can equal a
    # B+C value by chance. Every literal here is the rendering of a paper_d resolver value (a
    # within-run correct-vs-misclassified contrast, which Paper B+C does not compute), so each
    # coincidence is recorded as an exception scoped to this manuscript, naming its source.
    for literal, (cid, other) in sorted(collisions(claims).items()):
        lines += ["[[exclusivity_exception]]", f'file = "{MANUSCRIPT}"', f'text = "{literal}"',
                  f'reason = "Paper D value {cid} (paper_d resolver); equals {other} only by '
                  f'chance at this precision"', ""]
    for literal, reason in PROSE_CONSTANTS.items():
        lines += ["[[exclusivity_exception]]", f'file = "{MANUSCRIPT}"', f'text = "{literal}"',
                  f'reason = "{reason}"', ""]
    lines.append(END)
    block = "\n".join(lines)
    # Keep the registry's own line endings (read and write bytes, no newline translation).
    raw = REGISTRY.read_bytes().decode("utf-8")
    eol = "\r\n" if "\r\n" in raw else "\n"
    reg = raw.replace("\r\n", "\n")
    if BEGIN in reg:
        reg = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, reg, flags=re.DOTALL)
    else:
        reg = reg.rstrip("\n") + "\n\n" + block + "\n"
    REGISTRY.write_bytes(reg.replace("\n", eol).encode("utf-8"))
    print(f"rendered {MANUSCRIPT}; {len(claims)} claims registered")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
