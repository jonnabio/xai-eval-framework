#!/usr/bin/env python3
"""Register the paper values that the follow-up chapter of the thesis prints (ADR-0023).

The chapter thesis/estudios-de-seguimiento.qmd reports studies whose numbers are already
registered for their papers. Those registry blocks are generated by the paper builds and
cannot list a thesis site. This script mirrors each claim named in
pub/thesis_followup_claims.toml into the generated block `thesis_followup` of
pub/claim_registry.toml: same resolver, same value, same tolerance and the same printed
literal, with the thesis file as the site. verify_claims.py then re-derives the value and
checks that the chapter prints it (RCA-001).

`--check` writes nothing and fails unless the registry is what this script would write, so
a paper value that changes in a revision fails here until the chapter is brought level.

    python scripts/pubs/register_thesis_followup.py
"""
from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REGISTRY = ROOT / "pub" / "claim_registry.toml"
SELECTION = ROOT / "pub" / "thesis_followup_claims.toml"
PREFIX = "thesis_followup."
BEGIN = "# >>> thesis_followup generated by scripts/pubs/register_thesis_followup.py -- do not edit >>>"
END = "# <<< thesis_followup generated <<<"
# The paper scripts rewrite their own blocks after this point; this block stays before them.
BEFORE = "# >>> paper_d generated by scripts/pubs/render_paper_d.py"


def block_lines(reg: dict, selection: dict) -> list[str]:
    by_id = {c["id"]: c for c in reg.get("claim", [])}
    file = selection["file"]
    lines = [BEGIN,
             "# Paper values printed in the follow-up chapter of the thesis, mirrored from the",
             "# claims listed in pub/thesis_followup_claims.toml. Regenerated by the script.", ""]
    problems = []
    for cid in selection["claims"]:
        claim = by_id.get(cid)
        if claim is None:
            problems.append(f"{cid}: no such claim in the registry")
            continue
        texts = sorted({s["text"] for s in claim.get("appears_in", [])})
        if len(texts) != 1:
            problems.append(f"{cid}: printed as {texts}; one literal is needed")
            continue
        lines += ["[[claim]]", f'id = "{PREFIX}{cid}"', f'source = "{claim["source"]}"',
                  f'value = "{claim["value"]}"']
        if "tolerance" in claim:
            lines.append(f"tolerance = {claim['tolerance']:.10g}")
        lines += [f'appears_in = [{{ file = "{file}", text = "{texts[0]}" }}]', ""]
    if problems:
        sys.exit("thesis follow-up registration failed:\n" + "\n".join(f"- {p}" for p in problems))
    return lines + [END]


def registry_text() -> tuple[str, int]:
    raw = REGISTRY.read_bytes().decode("utf-8")
    eol = "\r\n" if "\r\n" in raw else "\n"
    reg = raw.replace("\r\n", "\n")
    reg = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n+", "", reg, flags=re.DOTALL)
    anchor = reg.find(BEFORE)
    if anchor < 0:
        sys.exit(f"the registry has no line starting with {BEFORE!r}")
    selection = tomllib.loads(SELECTION.read_text(encoding="utf-8"))
    lines = block_lines(tomllib.loads(reg), selection)
    text = reg[:anchor] + "\n".join(lines) + "\n\n" + reg[anchor:]
    return text.replace("\n", eol), len(selection["claims"])


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="Write nothing; fail if the registry is not what this script writes.")
    args = parser.parse_args(argv)
    text, n = registry_text()
    if REGISTRY.read_bytes().decode("utf-8") != text:
        if args.check:
            sys.exit("pub/claim_registry.toml is out of date; run "
                     "scripts/pubs/register_thesis_followup.py")
        REGISTRY.write_bytes(text.encode("utf-8"))
    print(f"OK: thesis follow-up chapter, {n} claims mirrored")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
