#!/usr/bin/env python3
"""Register every number printed in Paper F.

Paper F is rendered by docs/reports/paper_f/scripts/build_paper_f.py: each placeholder
<<alias:key:column:format>> of paper_f_template.tex is filled from a result file, and three
tables are generated from the same files. This script reads the same placeholders, through
the functions of that build, and writes the generated Paper F block of
pub/claim_registry.toml:

1. One claim per printed number with decimals (and per thousands-separated integer) of the
   manuscript, of Table 1 (generated/tab_datasets.tex) and of Table 2
   (generated/tab_primary.tex), re-derived by the `paper_f` resolver of claim_sources.py
   (RCA-001). Table 3 prints bare counts only.
2. Exclusivity exceptions for the Paper F files where one of their own registered values, or
   a structural constant, equals a result of an unpublished manuscript at the printed
   precision. A literal that neither accounts for is not excepted: the script stops and
   lists it. Paper F prints no result of another paper (analysis plan, section 5).

Integers without a thousands separator (counts, whole percentages) are outside the registry,
as for every manuscript. `--check` covers them: it fails unless paper_f.tex and Table 1 equal
what the build renders from the result files, and unless the registry is what this script
would write.

    python docs/reports/paper_f/scripts/build_paper_f.py     # lane paper-f
    python scripts/pubs/register_paper_f.py                  # shared files, through main
"""
from __future__ import annotations

import argparse
import importlib.util
import re
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from verify_claims import _as_number, _decimals, _literals, _read, _scannable  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
F = ROOT / "docs" / "reports" / "paper_f"
REGISTRY = ROOT / "pub" / "claim_registry.toml"
FOLDER = "docs/reports/paper_f/"
MANUSCRIPT = FOLDER + "paper_f.tex"
TAB_DATASETS = FOLDER + "generated/tab_datasets.tex"
TAB_PRIMARY = FOLDER + "generated/tab_primary.tex"
TAB_ADULT = FOLDER + "generated/tab_adult.tex"
FILES = (MANUSCRIPT, TAB_DATASETS, TAB_PRIMARY, TAB_ADULT)
BEGIN = "# >>> paper_f generated by scripts/pubs/register_paper_f.py -- do not edit >>>"
END = "# <<< paper_f generated <<<"
AFTER = "# >>> paper_c generated by scripts/pubs/register_paper_c.py"
# Columns of primary.csv printed in Table 2 by scripts/paper_f_report.py, two decimals each.
PRIMARY_COLUMNS = ("mean_rank_lime", "mean_rank_shap", "mean_rank_anchors", "mean_rank_dice",
                   "mean_rank_corr", "ci_low", "ci_high", "ceiling_seeds")


def _build_module():
    spec = importlib.util.spec_from_file_location("build_paper_f",
                                                  F / "scripts" / "build_paper_f.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _literal(v: float, f: str) -> tuple[str | None, int, float]:
    """Printed literal (None when the format prints a bare integer), decimals, scale."""
    if f in ("d", "w", "W", "pct"):
        return None, 0, 1.0
    if f == "int":
        s = f"{int(round(v)):,}"
        return (s if "," in s else None), 0, 1.0
    if f == "p":
        return (None if v < 0.001 else f"{v:.3f}"), 3, 1.0
    if f in ("pct1", "pct2"):
        return f"{100 * v:.{f[3]}f}", int(f[3]), 100.0
    if f in ("u2", "u3"):
        return f"{abs(v):.{f[1]}f}", int(f[1]), 1.0
    raise KeyError(f"unknown format {f}")


def collect(bpf) -> dict[str, dict]:
    """Claims by id: source, value, tolerance and the sites (file, printed text)."""
    data = bpf.tables()
    claims: dict[str, dict] = {}

    def add(alias: str, key: str, column: str, f: str, file: str) -> None:
        v = float(data[alias][key][column])
        literal, dec, scale = _literal(v, f)
        if literal is None:
            return
        number = literal.replace(",", "")
        negative = v < 0 and float(number) != 0
        cid = "paper_f." + ".".join([alias, key, column, f])
        claim = claims.setdefault(cid, {
            "source": f"paper_f:{alias}:{key}:{column}" + (":x100" if scale != 1 else ""),
            "value": ("-" if negative else "") + number,
            "tolerance": 0.5 if f == "int" else 0.5 * 10 ** -dec + 1e-9,
            "sites": set()})
        claim["sites"].add((file, literal))

    template = (F / "paper_f_template.tex").read_text(encoding="utf-8")
    for alias, key, column, f in bpf.TOKEN.findall(template):
        # The header comment of the template shows the placeholder syntax; it is no value.
        if alias in data and f not in ("outcome", "txt"):
            add(alias, key, column, f, MANUSCRIPT)
    for measure in data["prim"]:
        for column in PRIMARY_COLUMNS:
            add("prim", measure, column, "u2", TAB_PRIMARY)
    for key in data["data"]:
        add("data", key, "rows", "int", TAB_DATASETS)
        add("data", key, "minority_share", "pct1", TAB_DATASETS)
    return claims


def _collisions(reg_text: str) -> tuple[list[tuple[str, str, str]], list[str]]:
    """Literals of the Paper F files that equal a result of an unpublished manuscript by the
    rule of verify_claims._check_exclusivity: (file, literal, reason) to except, and
    unexplained."""
    reg = tomllib.loads(reg_text)
    cfg = reg.get("exclusivity") or {}
    forbid = tuple(cfg.get("forbid") or [])
    allow = tuple(cfg.get("allow_if_also") or [])
    structural = set((reg.get("coverage") or {}).get("structural") or [])
    excepted_all = {e["text"] for e in reg.get("exclusivity_exception", []) if "file" not in e}
    excepted_in: dict[str, set[str]] = {}
    for e in reg.get("exclusivity_exception", []):
        if "file" in e:
            excepted_in.setdefault(e["file"], set()).add(e["text"])

    def literals_of(claim: dict) -> set[str]:
        return {lit for s in claim.get("appears_in", []) for lit in _literals(s.get("text", ""))}

    def matches(literal: str, value: float, texts: set[str]) -> bool:
        return literal in texts or abs(abs(value) - float(literal)) <= (
            10 ** -_decimals(literal)) / 2 + 1e-12

    protected = []
    for claim in reg.get("claim", []):
        files = [s["file"] for s in claim.get("appears_in", [])]
        if any(f.startswith(forbid) for f in files) and not any(f.startswith(allow) for f in files):
            protected.append((claim["id"], _as_number(claim["value"]), literals_of(claim)))

    exceptions, unexplained = [], []
    for rel in FILES:
        if rel not in (cfg.get("files") or []):
            sys.exit(f"[exclusivity] files must list {rel}")
        local = [(c["id"], _as_number(c["value"]), literals_of(c)) for c in reg.get("claim", [])
                 if any(s["file"] == rel for s in c.get("appears_in", []))]
        skip = excepted_all | excepted_in.get(rel, set())
        seen: set[str] = set()
        for lineno, line in enumerate(_scannable(_read(ROOT / rel)).splitlines(), 1):
            for literal in sorted(_literals(line)):
                places = _decimals(literal)
                if (literal in skip or literal in seen or places == 0
                        or (places == 1 and float(literal) < 10)):
                    continue
                hit = next((cid for cid, v, t in protected if matches(literal, v, t)), None)
                if hit is None:
                    continue
                seen.add(literal)
                owner = next((cid for cid, v, t in local if matches(literal, v, t)), None)
                if owner:
                    exceptions.append((rel, literal, f"Value of {owner}, registered for this "
                                       f"file; equals {hit} only by chance at this precision"))
                elif literal in structural:
                    exceptions.append((rel, literal, f"Structural constant of the registry, not "
                                       f"a result; equals {hit} only by chance"))
                else:
                    unexplained.append(f"{rel}:{lineno} prints {literal}, which equals {hit} "
                                       "and is not a registered value of that file")
    return exceptions, unexplained


def registry_text(claims: dict[str, dict]) -> str:
    raw = REGISTRY.read_bytes().decode("utf-8")
    eol = "\r\n" if "\r\n" in raw else "\n"
    reg = raw.replace("\r\n", "\n")
    reg = re.sub(r"\n*" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n*", "\n\n", reg,
                 flags=re.DOTALL)
    # register_paper_c.py rewrites its block at the end of the file, so this block goes
    # before it; each script then leaves the other's block where it is.
    anchor = reg.find(AFTER)
    head = (reg if anchor < 0 else reg[:anchor]).rstrip("\n") + "\n"
    tail = "" if anchor < 0 else "\n" + reg[anchor:].rstrip("\n") + "\n"

    lines = [BEGIN,
             "# Every number with decimals printed in Paper F and in its Tables 1 and 2, re-derived",
             "# from outputs/analysis/paper_f/ by the paper_f resolver. Regenerated by the script;",
             "# edit paper_f_template.tex and rebuild instead.", ""]
    for cid, c in sorted(claims.items()):
        sites = ", ".join(f'{{ file = "{file}", text = "{text}" }}'
                          for file, text in sorted(c["sites"]))
        lines += ["[[claim]]", f'id = "{cid}"', f'source = "{c["source"]}"',
                  f'value = "{c["value"]}"', f"tolerance = {c['tolerance']:.10g}",
                  f"appears_in = [{sites}]", ""]

    exceptions, unexplained = _collisions(head + "\n" + "\n".join(lines + [END]) + "\n" + tail)
    if unexplained:
        sys.exit("a Paper F file prints a result of an unpublished manuscript that none of its "
                 "own claims accounts for:\n" + "\n".join(f"- {u}" for u in unexplained))
    if exceptions:
        lines += ["# Chance coincidences: a value of Paper F, or a structural constant, equals a",
                  "# result of an unpublished manuscript at the printed precision.", ""]
    for rel, literal, reason in sorted(exceptions):
        lines += ["[[exclusivity_exception]]", f'file = "{rel}"', f'text = "{literal}"',
                  f'reason = "{reason}"', ""]
    lines.append(END)
    return (head + "\n" + "\n".join(lines) + "\n" + tail).replace("\n", eol)


def _stale(bpf) -> list[str]:
    """Generated files that are not what the build renders from the result files."""
    out = []
    norm = lambda s: s.replace("\r\n", "\n")
    if norm((ROOT / MANUSCRIPT).read_text(encoding="utf-8")) != norm(bpf.HEADER + bpf.render_text()):
        out.append(MANUSCRIPT)
    if norm((ROOT / TAB_DATASETS).read_text(encoding="utf-8")) != norm(bpf.dataset_table()):
        out.append(TAB_DATASETS)
    return [f"{rel} is not what the build renders from the result files; run "
            "docs/reports/paper_f/scripts/build_paper_f.py" for rel in out]


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="Write nothing; fail if paper_f.tex or the registry is not what "
                             "the result files and the template give.")
    args = parser.parse_args(argv)

    bpf = _build_module()
    stale = _stale(bpf)
    if stale and not args.check:
        sys.exit("\n".join(stale))
    claims = collect(bpf)
    text = registry_text(claims)
    if REGISTRY.read_bytes().decode("utf-8") != text:
        if args.check:
            stale.append("pub/claim_registry.toml is out of date; run "
                         "scripts/pubs/register_paper_f.py")
        else:
            REGISTRY.write_bytes(text.encode("utf-8"))
    if stale:
        sys.exit("Paper F registration check failed:\n" + "\n".join(f"- {s}" for s in stale))
    n_sites = sum(len(c["sites"]) for c in claims.values())
    print(f"OK: Paper F, {len(claims)} claims, {n_sites} sites")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
