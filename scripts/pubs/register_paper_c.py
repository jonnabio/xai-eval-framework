#!/usr/bin/env python3
"""Register every number printed in Paper C, and keep its abstract in pub/claims.toml.

Paper C is rendered by docs/reports/paper_c/scripts/build_paper_c.py: each placeholder
<<alias:key:column:format>> of paper_c_template.tex is filled from a result file. This script
reads the same placeholders, through the functions of that build, and writes:

1. The generated Paper C block of pub/claim_registry.toml: one claim per printed number with
   decimals (and per thousands-separated integer), re-derived by the `paper_c` resolver of
   claim_sources.py (RCA-001).
2. Sites on existing claims. A quantity that another manuscript already carries (the
   agreement coefficients of the first panel and of the second panel's views, registered for
   the thesis and the 32-page edition) is registered once: Paper C is added to the
   `appears_in` of that claim, and no second claim is written.
3. Exclusivity exceptions for the other protected files (Paper D, Paper E, the chapter) where
   one of their own registered values equals a Paper C value at the printed precision. A
   literal that no claim of that file accounts for is not excepted: the script stops and
   lists it.
4. The [papers.paper_c] table of pub/claims.toml: abstract, keywords, resumen and palabras
   clave as paper_c.tex prints them. Run generate_fragments.py afterwards.

Integers without a thousands separator (counts, whole percentages) are outside the registry,
as for every manuscript. `--check` covers them: it fails unless paper_c.tex equals the
template rendered from the result files, and unless the registry and claims.toml are what
this script would write. CI runs it.

    python docs/reports/paper_c/scripts/build_paper_c.py     # lane paper-c
    python scripts/pubs/register_paper_c.py                  # shared files, through main
    python scripts/pubs/generate_fragments.py
"""
from __future__ import annotations

import argparse
import importlib.util
import re
import sys
import tomllib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from claim_sources import MissingArtifact, resolve  # noqa: E402
from verify_claims import _as_number, _decimals, _literals, _read, _scannable  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
C = ROOT / "docs" / "reports" / "paper_c"
REGISTRY = ROOT / "pub" / "claim_registry.toml"
CLAIMS = ROOT / "pub" / "claims.toml"
MANUSCRIPT = "docs/reports/paper_c/paper_c.tex"
FOLDER = "docs/reports/paper_c/"
BEGIN = "# >>> paper_c generated by scripts/pubs/register_paper_c.py -- do not edit >>>"
END = "# <<< paper_c generated <<<"
SITE_LINE = re.compile(
    r'^[ \t]*\{ file = "' + re.escape(MANUSCRIPT) + r'", text = "[^"]*" \},[ \t]*\n',
    re.MULTILINE)

_EXP4C2_STAT = {"icc_1_1": "icc", "ci_lower": "ci_lower", "ci_upper": "ci_upper",
                "krippendorff_alpha": "alpha", "n_cases": "n"}
_EXP4_STAT = {"icc_2_1": "icc", "icc_1_1": "icc", "ci_upper": "icc_ci_upper"}


def _build_module():
    spec = importlib.util.spec_from_file_location("build_paper_c",
                                                  C / "scripts" / "build_paper_c.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _literal(v: float, f: str) -> tuple[str | None, int, float]:
    """Registry literal (None when the format prints a bare integer), decimals, scale."""
    if f in ("d", "w", "pct"):
        return None, 0, 1.0
    if f == "int":
        s = f"{int(round(v)):,}"
        return (s if "," in s else None), 0, 1.0
    if f == "p":
        return (None if v < 0.001 else f"{v:.3f}"), 3, 1.0
    if f == "pct1":
        return f"{100 * v:.1f}", 1, 100.0
    if f in ("u2", "u3", "s2", "s3"):
        return f"{abs(v):.{f[1]}f}", int(f[1]), 1.0
    if f == "rs":
        return f"{abs(v):.2f}", 2, 1.0
    raise KeyError(f"unknown format {f}")


def _shared_source(alias: str, parts: tuple[str, ...], column: str, v: float) -> str | None:
    """Resolver expression of a quantity that is registered outside Paper C, or None."""
    candidate = None
    if alias == "view" and column in _EXP4C2_STAT:
        candidate = f"exp4c2:{parts[1]}:{_EXP4C2_STAT[column]}:{parts[0]}"
    elif alias == "rel" and parts[:2] == ("primary3", "all") and column in _EXP4C2_STAT:
        candidate = f"exp4c2:hidden_label_primary:{_EXP4C2_STAT[column]}:{parts[2]}"
    elif alias in ("orig", "first") and column in _EXP4_STAT:
        candidate = f"exp4:{_EXP4_STAT[column]}:{parts[0]}"
    elif alias == "alpha" and column == "krippendorff_alpha":
        candidate = f"exp4:alpha:{parts[0]}"
    if candidate is None:
        return None
    try:
        same = abs(resolve(candidate) - v) <= 1e-5
    except (MissingArtifact, KeyError, ValueError):
        return None
    return candidate if same else None


def collect(bpc) -> tuple[str, dict, dict]:
    """Render the template; return (text, own claims, shared literals by source)."""
    template = (C / "paper_c_template.tex").read_text(encoding="utf-8")
    own: dict[str, tuple[str, str, str, float]] = {}
    shared: dict[str, tuple[float, set[str]]] = {}

    def sub(m: re.Match) -> str:
        alias, key, column, f = m.groups()
        r = bpc.row(alias, key)
        v = float(r[column])
        literal, dec, scale = _literal(v, f)
        if literal is not None:
            parts = tuple(bpc.VIEWS.get(p, bpc.JUDGES.get(p, p)) for p in key.split("|"))
            source = _shared_source(alias, parts, column, v)
            if source:
                shared.setdefault(source, (v, set()))[1].add(literal)
            else:
                number = literal.replace(",", "")
                negative = v < 0 and float(number) != 0
                cid = "paper_c." + ".".join([alias, *key.split("|"), column, f])
                own[cid] = (
                    f"paper_c:{alias}:{'|'.join(parts)}:{column}" + (":x100" if scale != 1 else ""),
                    ("-" if negative else "") + number, literal,
                    0.5 if f == "int" else 0.5 * 10 ** -dec + 1e-9)
        return bpc.fmt(v, f, r)

    out = bpc.TOKEN.sub(sub, template)
    left = re.findall(r"<<[^>]*>>", out)
    if left:
        sys.exit(f"unresolved placeholders: {left[:5]}")
    return out, own, shared


def _add_sites(reg: str, source: str, literals: list[str]) -> str | None:
    """Add Paper C sites to the claim with this source; None when no such claim exists."""
    hits = list(re.finditer(r"^source = [\"']" + re.escape(source) + r"[\"'][ \t]*$", reg,
                            re.MULTILINE))
    if not hits:
        return None
    if len(hits) > 1:
        sys.exit(f"source {source} is registered {len(hits)} times; expected once")
    start = hits[0].end()
    end = reg.find("\n\n", start)
    end = len(reg) if end == -1 else end
    claim = reg[start:end]
    new = "".join(f'  {{ file = "{MANUSCRIPT}", text = "{lit}" }},\n' for lit in literals)
    multi = re.search(r"^appears_in = \[[ \t]*\n(.*?)^\]", claim, re.DOTALL | re.MULTILINE)
    single = re.search(r"^appears_in = \[(.*)\][ \t]*$", claim, re.MULTILINE)
    if multi:
        claim = claim[:multi.end(1)] + new + claim[multi.end(1):]
    elif single:
        inner = single.group(1).strip().rstrip(",")
        body = (f"  {inner},\n" if inner else "") + new
        claim = claim[:single.start()] + "appears_in = [\n" + body + "]" + claim[single.end():]
    elif "appears_in" in claim:
        sys.exit(f"cannot read the appears_in of the claim with source {source}")
    else:
        claim += "\nappears_in = [\n" + new + "]"
    return reg[:start] + claim + reg[end:]


def _collisions(reg_text: str) -> tuple[list[tuple[str, str, str]], list[str]]:
    """Literals of the other protected files that equal a Paper C value by the rule of
    verify_claims._check_exclusivity: (file, literal, reason) to except, and unexplained."""
    reg = tomllib.loads(reg_text)
    cfg = reg.get("exclusivity") or {}
    forbid = tuple(cfg.get("forbid") or [])
    if FOLDER not in forbid:
        sys.exit(f"[exclusivity] forbid must list {FOLDER}")
    others = tuple(f for f in forbid if f != FOLDER)
    allow = tuple(cfg.get("allow_if_also") or [])
    structural = set((reg.get("coverage") or {}).get("structural") or [])
    excepted_all = {e["text"] for e in reg.get("exclusivity_exception", []) if "file" not in e}
    excepted_in: dict[str, set[str]] = {}
    for e in reg.get("exclusivity_exception", []):
        if "file" in e:
            excepted_in.setdefault(e["file"], set()).add(e["text"])

    def literals_of(claim: dict) -> set[str]:
        return {lit for s in claim.get("appears_in", []) for lit in _literals(s.get("text", ""))}

    protected = []          # protected only because Paper C prints them
    for claim in reg.get("claim", []):
        files = [s["file"] for s in claim.get("appears_in", [])]
        if (any(f.startswith(FOLDER) for f in files)
                and not any(f.startswith(others) for f in files)
                and not any(f.startswith(allow) for f in files)):
            protected.append((claim["id"], _as_number(claim["value"]), literals_of(claim)))

    def matches(literal: str, value: float, texts: set[str]) -> bool:
        return literal in texts or abs(abs(value) - float(literal)) <= (
            10 ** -_decimals(literal)) / 2 + 1e-12

    exceptions, unexplained = [], []
    for rel in cfg.get("files") or []:
        path = ROOT / rel
        if not path.exists():
            continue
        local = [(c["id"], _as_number(c["value"]), literals_of(c)) for c in reg.get("claim", [])
                 if any(s["file"] == rel for s in c.get("appears_in", []))]
        skip = excepted_all | excepted_in.get(rel, set())
        seen: set[str] = set()
        for lineno, line in enumerate(_scannable(_read(path)).splitlines(), 1):
            for literal in sorted(_literals(line)):
                places = _decimals(literal)
                if (literal in skip or literal in seen or places == 0
                        or (places == 1 and float(literal) < 10)):
                    continue
                hit = next((cid for cid, v, t in protected if matches(literal, v, t)), None)
                if hit is None:
                    continue
                seen.add(literal)
                owner = next((cid for cid, v, t in local if cid != hit and matches(literal, v, t)),
                             None)
                if owner:
                    exceptions.append((rel, literal, f"Value of {owner}, registered for this "
                                       f"file; equals {hit} only by chance at this precision"))
                elif literal in structural:
                    exceptions.append((rel, literal, f"Structural constant of the registry, not "
                                       f"a result; equals {hit} only by chance"))
                else:
                    unexplained.append(f"{rel}:{lineno} prints {literal}, which equals {hit} "
                                       "and is not a registered value of that file")
    return exceptions, unexplained


def registry_text(own: dict, shared: dict) -> str:
    raw = REGISTRY.read_bytes().decode("utf-8")
    eol = "\r\n" if "\r\n" in raw else "\n"
    reg = raw.replace("\r\n", "\n")
    reg = re.sub(r"\n*" + re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n?", "\n", reg,
                 flags=re.DOTALL)
    reg = SITE_LINE.sub("", reg).rstrip("\n") + "\n"

    block_shared = []
    for source, (v, literals) in sorted(shared.items()):
        updated = _add_sites(reg, source, sorted(literals))
        if updated is None:
            block_shared.append((source, v, sorted(literals)))
        else:
            reg = updated

    lines = [BEGIN,
             "# Every number with decimals printed in Paper C, re-derived from the result files of",
             "# docs/reports/paper_c/results/ by the paper_c resolver. Quantities that another",
             "# manuscript also carries are sites on their existing claims, not claims here.",
             "# Regenerated by the script; edit paper_c_template.tex and rebuild instead.", ""]
    for source, v, literals in block_shared:
        dec = max(_decimals(lit) for lit in literals)
        sites = ", ".join(f'{{ file = "{MANUSCRIPT}", text = "{lit}" }}' for lit in literals)
        lines += ["[[claim]]", f'id = "paper_c.shared.{source.replace(":", ".")}"',
                  f'source = "{source}"', f'value = "{v:.4f}"',
                  f"tolerance = {0.5 * 10 ** -dec + 1e-9:.10g}", f"appears_in = [{sites}]", ""]
    for cid, (source, value, literal, tol) in sorted(own.items()):
        lines += ["[[claim]]", f'id = "{cid}"', f'source = "{source}"', f'value = "{value}"',
                  f"tolerance = {tol:.10g}",
                  f'appears_in = [{{ file = "{MANUSCRIPT}", text = "{literal}" }}]', ""]

    exceptions, unexplained = _collisions(reg + "\n" + "\n".join(lines + [END]) + "\n")
    if unexplained:
        sys.exit("a protected file prints a Paper C value that none of its own claims "
                 "accounts for:\n" + "\n".join(f"- {u}" for u in unexplained))
    if exceptions:
        lines += ["# Chance coincidences: a registered value of another protected file equals a",
                  "# Paper C value at the printed precision. Each names the claim of that file.", ""]
    for rel, literal, reason in sorted(exceptions):
        lines += ["[[exclusivity_exception]]", f'file = "{rel}"', f'text = "{literal}"',
                  f'reason = "{reason}"', ""]
    lines.append(END)
    return (reg + "\n" + "\n".join(lines) + "\n").replace("\n", eol)


def _between(tex: str, start: str, stop: str) -> str:
    m = re.search(re.escape(start) + r"(.*?)" + re.escape(stop), tex, re.DOTALL)
    if not m:
        sys.exit(f"{MANUSCRIPT}: no text between {start!r} and {stop!r}")
    return m.group(1).strip()


def front_matter(tex: str) -> dict[str, str]:
    """Abstract, keywords, resumen and palabras clave as the manuscript prints them."""
    one_line = lambda s: " ".join(s.split()).rstrip(".")
    return {
        "abstract_en_tex": _between(tex, "\\section*{Abstract}\n",
                                    "\\noindent\\textbf{Keywords:}"),
        "keywords_en_tex": one_line(_between(tex, "\\noindent\\textbf{Keywords:}",
                                             "\\section*{Resumen}")),
        "abstract_es_tex": _between(tex, "\\section*{Resumen}\n",
                                    "\\noindent\\textbf{Palabras clave:}"),
        "keywords_es_tex": one_line(_between(tex, "\\noindent\\textbf{Palabras clave:}",
                                             "\\section{Introduction}")),
    }


def claims_text(tex: str) -> str:
    raw = CLAIMS.read_bytes().decode("utf-8")
    eol = "\r\n" if "\r\n" in raw else "\n"
    src = raw.replace("\r\n", "\n")
    parts = front_matter(tex)
    table = ["[papers.paper_c]"]
    for key, text in parts.items():
        if '"' in text:
            sys.exit(f"{key}: a double quote cannot be written to claims.toml by this script")
        text = text.replace("\\", "\\\\")       # RCA-003: every LaTeX backslash doubled
        table.append(f'{key} = """\n{text}\n"""' if key.startswith("abstract")
                     else f'{key} = "{text}"')
    new, n = re.subn(r"^\[papers\.paper_c\]\n.*?(?=^\[|\Z)", lambda _: "\n".join(table) + "\n",
                     src, flags=re.DOTALL | re.MULTILINE)
    if n != 1:
        sys.exit("pub/claims.toml: expected one [papers.paper_c] table")
    return new.replace("\n", eol)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="Write nothing; fail if paper_c.tex, the registry or claims.toml "
                             "is not what the result files and the template give.")
    args = parser.parse_args(argv)

    rendered, own, shared = collect(_build_module())
    tex = (ROOT / MANUSCRIPT).read_text(encoding="utf-8").replace("\r\n", "\n")
    body = tex.split("\n", 1)[1] if tex.startswith("%% GENERATED") else tex
    stale = []
    if body != rendered.replace("\r\n", "\n"):
        stale.append(f"{MANUSCRIPT} is not the template rendered from the result files; "
                     "run docs/reports/paper_c/scripts/build_paper_c.py")
        if not args.check:
            sys.exit(stale[0])
    targets = [(REGISTRY, registry_text(own, shared)), (CLAIMS, claims_text(tex))]
    for path, text in targets:
        if path.read_bytes().decode("utf-8") != text:
            if args.check:
                stale.append(f"{path.relative_to(ROOT).as_posix()} is out of date; "
                             "run scripts/pubs/register_paper_c.py")
            else:
                path.write_bytes(text.encode("utf-8"))
    if stale:
        sys.exit("Paper C registration check failed:\n" + "\n".join(f"- {s}" for s in stale))
    n_sites = sum(len(lits) for _, lits in shared.values())
    print(f"OK: Paper C, {len(own)} claims of its own, {n_sites} site(s) on {len(shared)} "
          f"quantities shared with other manuscripts"
          + ("" if args.check else "; run scripts/pubs/generate_fragments.py"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
