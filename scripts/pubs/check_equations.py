#!/usr/bin/env python3
"""Every displayed equation and every figure of the thesis is numbered and cited
(author rule, 2026-10-12; extended to figures on 2026-10-13).

For the Quarto sources under thesis/, fails when
  1. a displayed equation ($$ ... $$) has no label `{#eq-...}` after it;
  2. a label is used twice;
  3. a labelled equation is never cited as `@eq-...` in the thesis;
  4. a citation `@eq-...` names no equation;
  5. a figure (`![caption](file)`) has no label `{#fig-...}`, a figure label is used twice
     or is never cited as `@fig-...`, or a citation `@fig-...` names no figure.

Tables are reported, not enforced: `--tables` lists the labelled tables no text cites.

The numbers themselves are generated by Quarto; none is typed. Standard library only.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
THESIS = ROOT / "thesis"

_FENCED = re.compile(r"```.*?```", re.DOTALL)
_DISPLAY = re.compile(r"\$\$.+?\$\$(?:[ \t]*\{#(eq-[\w-]+)\})?", re.DOTALL)
_CITED = re.compile(r"@(eq-[\w-]*\w)")
_FIGURE = re.compile(r"!\[.*?\]\([^)\n]*\)(\{[^}]*\})?", re.DOTALL)
_FIG_LABEL = re.compile(r"#(fig-[\w-]+)")
_FIG_CITED = re.compile(r"@(fig-[\w-]*\w)")
_TBL_LABEL = re.compile(r"\{#(tbl-[\w-]+)")
_TBL_CITED = re.compile(r"@(tbl-[\w-]*\w)")


def problems(folder: Path = THESIS) -> list[str]:
    found: list[str] = []
    defined: dict[str, str] = {}
    cited: dict[str, str] = {}
    for path in sorted(folder.glob("*.qmd")):
        text = _FENCED.sub(lambda m: "\n" * m.group(0).count("\n"), path.read_text(encoding="utf-8"))
        for m in _DISPLAY.finditer(text):
            line = text.count("\n", 0, m.start()) + 1
            label = m.group(1)
            if label is None:
                found.append(f"{path.name}:{line} displayed equation without a label {{#eq-...}}")
            elif label in defined:
                found.append(f"{path.name}:{line} label {label} is already used in {defined[label]}")
            else:
                defined[label] = f"{path.name}:{line}"
        for m in _CITED.finditer(_DISPLAY.sub(" ", text)):
            cited.setdefault(m.group(1), f"{path.name}:{text.count(chr(10), 0, m.start()) + 1}")
    for label, where in defined.items():
        if label not in cited:
            found.append(f"{where} equation {label} is never cited in the text (@{label})")
    for label, where in cited.items():
        if label not in defined:
            found.append(f"{where} cites @{label}, which labels no equation")
    return found + figure_problems(folder)


def figure_problems(folder: Path = THESIS) -> list[str]:
    found: list[str] = []
    defined: dict[str, str] = {}
    cited: dict[str, str] = {}
    for path in sorted(folder.glob("*.qmd")):
        text = _FENCED.sub(lambda m: "\n" * m.group(0).count("\n"), path.read_text(encoding="utf-8"))
        for m in _FIGURE.finditer(text):
            where = f"{path.name}:{text.count(chr(10), 0, m.start()) + 1}"
            label = _FIG_LABEL.search(m.group(1) or "")
            if label is None:
                found.append(f"{where} figure without a label {{#fig-...}}")
            elif label.group(1) in defined:
                found.append(f"{where} label {label.group(1)} is already used in {defined[label.group(1)]}")
            else:
                defined[label.group(1)] = where
        for m in _FIG_CITED.finditer(text):
            cited.setdefault(m.group(1), f"{path.name}:{text.count(chr(10), 0, m.start()) + 1}")
    for label, where in defined.items():
        if label not in cited:
            found.append(f"{where} figure {label} is never cited in the text (@{label})")
    for label, where in cited.items():
        if label not in defined:
            found.append(f"{where} cites @{label}, which labels no figure")
    return found


def uncited_tables(folder: Path = THESIS) -> list[str]:
    texts = {p.name: p.read_text(encoding="utf-8") for p in sorted(folder.glob("*.qmd"))}
    cited = {c for t in texts.values() for c in _TBL_CITED.findall(t)}
    return [f"{name}: {label}" for name, t in texts.items()
            for label in _TBL_LABEL.findall(t) if label not in cited]


def main() -> int:
    if "--tables" in sys.argv[1:]:
        tables = uncited_tables()
        print("\n".join(tables) or "every labelled table is cited")
        return 0
    found = problems()
    for p in found:
        print(f"FAIL: {p}", file=sys.stderr)
    if not found:
        n = sum(len(_DISPLAY.findall(p.read_text(encoding="utf-8"))) for p in THESIS.glob("*.qmd"))
        figures = sum(len(_FIGURE.findall(p.read_text(encoding="utf-8"))) for p in THESIS.glob("*.qmd"))
        print(f"OK: {n} displayed equation(s) and {figures} figure(s) of the thesis, "
              "each numbered and cited")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
