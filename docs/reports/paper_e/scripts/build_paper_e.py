def src(table: str, column: str, **filters: object) -> str:
    return f"paper_e:{table}:" + ",".join(f"{k}={v}" for k, v in filters.items()) + f":{column}"


class Numbers:
    def __init__(self) -> None:
        self.file = MANUSCRIPT
        self.claims: dict[tuple[str, str], dict] = {}

    def show(self, source: str, kind: str = "f3") -> str:
        """Printed text of a source expression; kind is f3, f2 or int."""
        value = resolve(source)
        if kind == "int":
            registered, literal, tolerance = str(int(round(value))), f"{int(round(value)):,}", 0.5
            text = literal
            if "," not in literal:        # a bare small integer is structural, not registered
                return text
        else:
            dec = int(kind[1])
            rounded = round(value, dec) + 0.0
            registered, literal = f"{rounded:.{dec}f}", f"{abs(rounded):.{dec}f}"
            tolerance = 0.5 * 10 ** -dec + 1e-9
            text = ("$-$" if rounded < 0 else "") + literal
        claim = self.claims.setdefault((source, kind), {
            "value": registered, "tolerance": tolerance, "sites": set()})
        claim["sites"].add((self.file, literal))
        return text

    def ci(self, source_low: str, source_high: str) -> str:
        return f"[{self.show(source_low)}, {self.show(source_high)}]"


def agreement_source(dataset: str, model: str, metric: str, column: str) -> str:
    """Agreement for a dataset/model; Adult model rows pool the three intensities."""
    if dataset == "exp2_adult" and model != "all":
        return src("posthoc/adult_margin_summary", column, model=model, intensity="all", metric=metric)
    return src("analysis/group_agreement_summary", column, dataset=dataset, model=model, metric=metric)


def correctness_source(dataset: str, model: str, column: str) -> str:
    intensity = "all" if dataset == "exp2_adult" else "not_applicable"
    return src("analysis/correctness_group_summary", column, dataset=dataset, model=model, intensity=intensity)


SCALARS = {
    "paired": "paper_e:analysis/pairing_diagnostics::sum(matched_ids)",
    "blocks": "paper_e:analysis/pairing_diagnostics::count()",
    "exact_blocks": "paper_e:analysis/pairing_diagnostics:same_id_sets=True:count()",
    "unpaired": "paper_e:analysis/pairing_diagnostics::sum(left_only_ids+right_only_ids)",
    "invalid_rows": "paper_e:analysis/run_inventory::sum(invalid_rows)",
    "primary_runs": "paper_e:analysis/run_agreement_summary::count()",
    "tau_undefined": "paper_e:analysis/instance_agreement::empty(kendall_tau_b)",
    "sign_undefined": "paper_e:analysis/instance_agreement::empty(sign_agreement)",
}
CORRECTNESS_COLUMN = {"diff": "mean_misclassified_minus_correct", "lo": LO, "hi": HI,
                      "correct": "mean_correct_jaccard", "mis": "mean_misclassified_jaccard"}
FIELD = {"est": EST, "lo": LO, "hi": HI}


def placeholder(numbers: Numbers, spec: str) -> str:
    kind, *a = spec.split("|")
    if kind == "n":
        if a[0].startswith("inst_"):
            return numbers.show(src("analysis/run_agreement_summary", "sum(n_instances)", dataset=a[0][5:]), "int")
        if a[0].startswith("runs_"):
            return numbers.show(src("analysis/run_agreement_summary", "count()", dataset=a[0][5:]), "int")
        return numbers.show(SCALARS[a[0]], "int")
    if kind == "agree":      # dataset|model|metric|field
        return numbers.show(agreement_source(a[0], a[1], a[2], FIELD[a[3]]))
    if kind == "int":        # intensity|metric|field
        return numbers.show(src("posthoc/adult_margin_summary", FIELD[a[2]], model="all", intensity=a[0], metric=a[1]))
    if kind == "sign":       # dataset|model|class|field
        return numbers.show(src("posthoc/sign_by_predicted_class_summary", FIELD[a[3]],
                                dataset=a[0], model=a[1], predicted_class=a[2]))
    if kind == "const":      # dataset|model|method|field
        return numbers.show(src("posthoc/sign_constancy_summary", FIELD[a[3]], dataset=a[0], model=a[1], method=a[2]))
    if kind == "corr":       # dataset|model|column
        return numbers.show(correctness_source(a[0], a[1], CORRECTNESS_COLUMN[a[2]]))
    if kind == "qual":       # dataset|model|metric
        return numbers.show(src("analysis/quality_association_summary", "mean_seed_spearman_rho",
                                dataset=a[0], model=a[1], quality_metric=a[2]), "f2")
    if kind == "qrange":     # dataset|metric|min or max   (over model families)
        return numbers.show(src("analysis/quality_association_summary", f"{a[2]}(mean_seed_spearman_rho)",
                                dataset=a[0], quality_metric=a[1]), "f2")
    if kind == "sec":        # pair|model|field
        return numbers.show(src("posthoc/secondary_group_summary", FIELD[a[2]], method_pair=a[0], model=a[1]))
    if kind == "chance":     # dataset|5 or 10
        return numbers.show(src("posthoc/chance_overlap", f"expected_top{a[1]}_jaccard", dataset=a[0]))
    raise SystemExit(f"unknown placeholder <<{spec}>>")


