def table_agreement(n: Numbers) -> str:
    lines = []
    for dataset, label in DATASETS:
        models = (ADULT_MODELS if dataset == "exp2_adult" else EXP3_MODELS) + ["all"]
        for k, model in enumerate(models):
            cells = [n.show(agreement_source(dataset, model, metric, EST)) + " "
                     + n.ci(agreement_source(dataset, model, metric, LO), agreement_source(dataset, model, metric, HI))
                     for metric in ("top5_jaccard", "top10_jaccard", "kendall_tau_b")]
            runs = n.show(agreement_source(dataset, model, "top5_jaccard", "n_runs"), "int")
            pairs = n.show(agreement_source(dataset, model, "top5_jaccard", "n_instances"), "int")
            lines.append(f"{label if k == 0 else ''} & {MODEL_LABEL[model]} & {runs} & {pairs} & "
                         + " & ".join(cells) + r" \\")
        lines.append(r"\hline")
    return "\n".join(lines) + "\n"


def table_sign(n: Numbers) -> str:
    lines = []
    for dataset, label in DATASETS:
        models = (ADULT_MODELS if dataset == "exp2_adult" else EXP3_MODELS) + ["all"]
        for k, model in enumerate(models):
            cells = [n.show(agreement_source(dataset, model, "sign_agreement", EST))]
            cells += [n.show(src("posthoc/sign_by_predicted_class_summary", EST, dataset=dataset, model=model,
                                 predicted_class=cls)) for cls in (0, 1)]
            cells += [n.show(src("posthoc/sign_constancy_summary", EST, dataset=dataset, model=model, method=m))
                      for m in ("shap", "lime")]
            lines.append(f"{label if k == 0 else ''} & {MODEL_LABEL[model]} & " + " & ".join(cells) + r" \\")
        lines.append(r"\hline")
    return "\n".join(lines) + "\n"


def table_correctness(n: Numbers) -> str:
    lines = []
    for dataset, model in GROUPS:
        if dataset == "breast_cancer":
            continue
        s = lambda column: correctness_source(dataset, model, column)  # noqa: E731
        negative = n.show(s("n_negative_seed_differences"), "int")
        seeds = n.show(s("n_seed_units"), "int")
        name = "Adult" if dataset == "exp2_adult" else "GC"
        lines.append(f"{name} & {MODEL_LABEL[model]} & {n.show(s('mean_correct_jaccard'))} & "
                     f"{n.show(s('mean_misclassified_jaccard'))} & {n.show(s('mean_misclassified_minus_correct'))} & "
                     f"{n.ci(s(LO), s(HI))} & {negative}/{seeds}" + r" \\")
    lines.append(r"\hline")  # the rule is in the generated file: \hline after \input fails
    return "\n".join(lines) + "\n"


