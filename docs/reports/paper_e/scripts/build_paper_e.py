# --- render, register, compile ------------------------------------------------

def render() -> Numbers:
    numbers = Numbers()
    (D / "tables").mkdir(exist_ok=True)
    for name, fn in TABLES.items():
        numbers.file = TABLE_FILE.format(name)
        (D / "tables" / f"{name}.tex").write_bytes(
            ("% GENERATED by scripts/build_paper_e.py -- do not edit\n" + fn(numbers)).encode("utf-8"))
    numbers.file = MANUSCRIPT
    template = (D / "paper_e_template.tex").read_text(encoding="utf-8")
    body = re.sub(r"<<([^<>]+)>>", lambda m: placeholder(numbers, m.group(1)), template)
    header = ("%% GENERATED from paper_e_template.tex by docs/reports/paper_e/scripts/build_paper_e.py.\n"
              "%% Do not edit: change the template and rebuild.\n")
    (D / "paper_e.tex").write_bytes((header + body).encode("utf-8"))
    print(f"rendered paper_e.tex and {len(TABLES)} tables; {len(numbers.claims)} claims")
    return numbers


def collisions(numbers: Numbers) -> dict[tuple[str, str], tuple[str, str]]:
    """Printed literals that equal, at their precision, a protected Paper B+C result."""
    reg = tomllib.loads(REGISTRY.read_text(encoding="utf-8"))
    cfg = reg.get("exclusivity") or {}
    forbid, allow = tuple(cfg.get("forbid") or []), tuple(cfg.get("allow_if_also") or [])
    protected = []
    for c in reg.get("claim", []):
        files = [s["file"] for s in c.get("appears_in", [])]
        if any(f.startswith(forbid) for f in files) and not any(f.startswith(allow) for f in files):
            texts = {t.replace(",", "") for site in c["appears_in"]
                     for t in re.findall(r"\d[\d,]*\.\d+|\d{1,3}(?:,\d{3})+", site.get("text", ""))}
            protected.append((c["id"], abs(float(c["value"].replace(",", "").replace("$", ""))), texts))
    out = {}
    for (source, _), claim in numbers.claims.items():
        for file, literal in claim["sites"]:
            if "," in literal:
                continue
            dec = len(literal.split(".")[1])
            for pid, value, texts in protected:    # same rule as verify_claims._check_exclusivity
                if literal in texts or abs(value - float(literal)) <= 0.5 * 10 ** -dec + 1e-12:
                    out.setdefault((file, literal), (source, pid))
                    break
    return out


def register(numbers: Numbers) -> None:
    lines = [BEGIN,
             "# Every number printed in Paper E, re-derived from outputs/analysis/paper_e/ by the",
             "# paper_e resolver. Regenerated on each build; edit paper_e_template.tex instead.", ""]
    for (source, kind), claim in sorted(numbers.claims.items()):
        slug = re.sub(r"[^A-Za-z0-9]+", "_", source.split(":", 1)[1]).strip("_")
        sites = ", ".join(f'{{ file = "{f}", text = "{t}" }}' for f, t in sorted(claim["sites"]))
        lines += ["[[claim]]", f'id = "paper_e.{slug}.{kind}"', f'source = "{source}"',
                  f'value = "{claim["value"]}"', f'tolerance = {claim["tolerance"]:.10g}',
                  f"appears_in = [{sites}]", ""]
    # Chance coincidences with results of the unpublished Paper B+C. The exclusivity check
    # matches by value at the printed precision, so a short decimal can equal a B+C value by
    # chance. Every literal here is an agreement or association statistic of the paper_e
    # resolver, which Paper B+C does not compute; each exception names its source.
    for (file, literal), (source, other) in sorted(collisions(numbers).items()):
        lines += ["[[exclusivity_exception]]", f'file = "{file}"', f'text = "{literal}"',
                  f'reason = "Paper E value {source}; equals {other} only by chance at this precision"', ""]
    lines.append(END)
    block = "\n".join(lines)
    raw = REGISTRY.read_bytes().decode("utf-8")
    eol = "\r\n" if "\r\n" in raw else "\n"
    reg = raw.replace("\r\n", "\n")
    if BEGIN in reg:
        reg = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, reg, flags=re.DOTALL)
    else:
        reg = reg.rstrip("\n") + "\n\n" + block + "\n"
    REGISTRY.write_bytes(reg.replace("\n", eol).encode("utf-8"))
    print(f"registered {len(numbers.claims)} claims in pub/claim_registry.toml")


def compile_pdf() -> None:
    tectonic = next((p for p in TECTONIC_CANDIDATES if p.exists()), None) or shutil.which("tectonic")
    if not tectonic:
        raise SystemExit("tectonic not found; see README.md, 'Build'")
    out = D / "submission"
    out.mkdir(exist_ok=True)
    for name, prefix in (("paper_e_blind", ""), ("paper_e_full", "\\def\\fullversion{}")):
        wrapper = D / f"{name}.tex"
        wrapper.write_text(prefix + "\\input{paper_e.tex}\n", encoding="utf-8")
        try:
            run = subprocess.run([str(tectonic), "--keep-logs", "--outdir", str(out), wrapper.name],
                                 cwd=D, capture_output=True, text=True, encoding="utf-8", errors="replace")
        finally:
            wrapper.unlink()
        if run.returncode:
            print(run.stderr[-3000:])
            raise SystemExit(f"tectonic failed for {name}")
        log = (out / f"{name}.log").read_text(encoding="utf-8", errors="replace")
        for junk in out.glob(f"{name}.*"):
            if junk.suffix != ".pdf":
                junk.unlink()
        problems = sorted(set(re.findall(r"(?:Reference|Citation) `[^']+' on page \d+ undefined|"
                                         r"Overfull \\hbox \((?:[2-9]\d|\d{3,})[^)]*\)", log)))
        for line in problems:
            print(f"  {name}: {line}")
        pages = int(re.search(r"Output written on .*?\((\d+) pages?", log).group(1))
        print(f"built submission/{name}.pdf ({pages} pages)")
        if pages > MAX_PAGES:
            raise SystemExit(f"{name}.pdf has {pages} pages; the limit set for this paper is {MAX_PAGES}")


