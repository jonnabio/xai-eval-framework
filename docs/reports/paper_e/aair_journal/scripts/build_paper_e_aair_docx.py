# --- numbers: the CyS build's resolver, placeholders and tables ---------------------

def cys_build():
    spec = importlib.util.spec_from_file_location("build_paper_e", E / "scripts" / "build_paper_e.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def render() -> tuple[str, object]:
    """paper_e_aair.tex: placeholders and \\input tables resolved, each number registered."""
    b = cys_build()
    numbers = b.Numbers()
    numbers.file = SITE
    tex = SOURCE.read_text(encoding="utf-8")

    def table(m: re.Match) -> str:
        return b.TABLES[m.group(1)](numbers).rstrip("\n")

    tex = re.sub(r"\\input\{tables/(\w+)\.tex\}", table, tex)
    tex = re.sub(r"<<([^<>]+)>>", lambda m: b.placeholder(numbers, m.group(1)), tex)
    if "<<" in tex or "\\input{" in tex:
        sys.exit("a placeholder or a table input is left unresolved")
    header = ("%% GENERATED from paper_e_aair_template.tex by scripts/build_paper_e_aair_docx.py.\n"
              "%% Do not edit: change the template and rebuild.\n")
    RENDERED.write_bytes((header + tex).encode("utf-8"))
    return tex, (b, numbers)


def register(build_and_numbers) -> int:
    b, numbers = build_and_numbers
    lines = [BEGIN,
             "# Every number printed in the AAIR edition of Paper E, re-derived from",
             "# outputs/analysis/paper_e/ by the paper_e resolver. Regenerated on each build;",
             "# edit docs/reports/paper_e/aair_journal/paper_e_aair_template.tex instead.", ""]
    for (source, kind), claim in sorted(numbers.claims.items()):
        slug = re.sub(r"[^A-Za-z0-9]+", "_", source.split(":", 1)[1]).strip("_")
        sites = ", ".join(f'{{ file = "{f}", text = "{t}" }}' for f, t in sorted(claim["sites"]))
        lines += ["[[claim]]", f'id = "paper_e_aair.{slug}.{kind}"', f'source = "{source}"',
                  f'value = "{claim["value"]}"', f'tolerance = {claim["tolerance"]:.10g}',
                  f"appears_in = [{sites}]", ""]
    # Same rule as the CyS build: chance coincidences, at the printed precision, with a
    # protected Paper B+C value.
    for (file, literal), (source, other) in sorted(b.collisions(numbers).items()):
        lines += ["[[exclusivity_exception]]", f'file = "{file}"', f'text = "{literal}"',
                  f'reason = "Paper E value {source}; equals {other} only by chance at this precision"', ""]
    lines.append(END)
    block = "\n".join(lines)
    raw = REGISTRY.read_bytes().decode("utf-8")
    eol = "\r\n" if "\r\n" in raw else "\n"
    reg = raw.replace("\r\n", "\n")
    if BEGIN in reg:
        reg = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, reg, flags=re.DOTALL)
    else:
        # Right after the CyS block: scripts/pubs/register_paper_c.py keeps its own block last.
        anchor = b.END + "\n"
        if reg.count(anchor) != 1:
            sys.exit("the generated Paper E block of the registry was not found")
        reg = reg.replace(anchor, anchor + "\n" + block + "\n", 1)
    REGISTRY.write_bytes(reg.replace("\n", eol).encode("utf-8"))
    return len(numbers.claims)


