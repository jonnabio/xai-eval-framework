def build_copyright_form(tex: str) -> Path:
    title = macro(tex, "title")
    out = OUT / f"{NAME}_copyright_form.docx"
    with zipfile.ZipFile(COPYRIGHT_TEMPLATE) as zt:
        doc = zt.read("word/document.xml").decode("utf-8")
    paras = re.findall(r"<w:p(?: [^>]*)?>.*?</w:p>", doc, flags=re.DOTALL)
    p = next(p for p in paras if text_of(p).strip().startswith("All authors of the manuscript titled"))
    runs = re.findall(r"<w:r(?: [^>]*)?>.*?</w:r>", p, flags=re.DOTALL)
    rpr = re.search(r"<w:rPr>.*?</w:rPr>", next(r for r in runs if "<w:t" in r), flags=re.DOTALL)
    rpr = rpr.group(0) if rpr else ""
    new = p[:p.index(runs[0])] + (f'<w:r>{rpr}<w:t xml:space="preserve">All authors of the manuscript '
                                  f'titled: \u201c{escape(title)}\u201d </w:t></w:r>') + "</w:p>"
    doc = doc.replace(p, new, 1)
    # First author row of the table and the corresponding author's name.
    row = next(c for c in re.findall(r"<w:p(?: [^>]*)?>.*?</w:p>", doc, flags=re.DOTALL)
               if text_of(c).strip().startswith("1\u2026"))
    doc = doc.replace(row, replace_text(row, f"1. {AUTHOR}"), 1)
    name = next(c for c in re.findall(r"<w:p(?: [^>]*)?>.*?</w:p>", doc, flags=re.DOTALL)
                if text_of(c).strip().startswith("Name Surname"))
    doc = doc.replace(name, replace_text(name, f"Name Surname: {AUTHOR}    E-mail: {EMAIL}"), 1)
    write_package(COPYRIGHT_TEMPLATE, out, doc, None, {}, title, AUTHOR)
    return out


WORD_SCRIPT = r"""
$ErrorActionPreference = 'Stop'
$word = New-Object -ComObject Word.Application
$word.Visible = $false
$word.DisplayAlerts = 0
try {
  $doc = $word.Documents.Open($args[0], $false, $false)
  if ($args[2] -eq "fields") { $doc.Fields.Update() | Out-Null }
  $doc.Repaginate()
  $pages = $doc.ComputeStatistics(2)
  $words = $doc.ComputeStatistics(0)
  $doc.Save()
  $doc.ExportAsFixedFormat($args[1], 17, $false, 0, 0, 0, 0, 0, $false)
  $doc.Close($false)
  Write-Output "pages=$pages words=$words"
} finally { $word.Quit() }
"""


def word_pass(docx: Path, title: str, creator: str, fields: bool = True) -> int:
    """Pages counted by Word, and the PDF. The copyright form keeps its fields: one of them
    loads the journal's logo from the web, which makes Word wait on a dialog."""
    script = OUT / "_word.ps1"
    script.write_text(WORD_SCRIPT, encoding="utf-8")
    pdf = docx.with_suffix(".pdf")
    try:
        r = subprocess.run(["powershell", "-NoProfile", "-ExecutionPolicy", "Bypass", "-File",
                            str(script), str(docx), str(pdf), "fields" if fields else "keep"], capture_output=True, text=True)
    finally:
        script.unlink(missing_ok=True)
    m = re.search(r"pages=(\d+) words=(\d+)", r.stdout)
    if r.returncode or not m:
        sys.exit(f"Word failed on {docx.name}:\n{r.stdout[-1500:]}\n{r.stderr[-1500:]}")
    tmp = docx.with_suffix(".tmp")
    with zipfile.ZipFile(docx) as zin, zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
        for n in zin.namelist():
            data = zin.read(n)
            if n == "docProps/core.xml":
                data = core_properties(data.decode("utf-8"), title, creator).encode("utf-8")
            zout.writestr(n, data)
    tmp.replace(docx)
    return int(m.group(1))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--no-pdf", action="store_true", help="do not open Word")
    args = ap.parse_args()
    for f in (TEMPLATE, LETTER_TEMPLATE, COPYRIGHT_TEMPLATE):
        if not f.exists():
            sys.exit(f"{f.relative_to(ROOT)} is missing; download it from the journal site "
                     "(AAIR_SUBMISSION.md)")
    if shutil.which("quarto") is None:
        sys.exit("quarto (for its pandoc) is not installed")
    OUT.mkdir(exist_ok=True)
    tex, numbers = render()
    print(f"rendered {RENDERED.relative_to(ROOT)}; registered {register(numbers)} claims")
    manuscript, count = build_manuscript(tex)
    floats = count["tables"] + count["figures"]
    print(f"manuscript: {count['tables']} tables + {count['figures']} figures = {floats}, "
          f"{count['equations']} equations, {count['references']} references, "
          f"abstract {count['abstract_words']} words, {count['keywords']} keywords")
    if floats > MAX_FLOATS or count["references"] > MAX_REFS:
        sys.exit("over the journal's limit of figures and tables or of references")
    built = [(manuscript, RUNNING_HEAD), (build_cover_letter(tex), macro(tex, "title")),
             (build_copyright_form(tex), macro(tex, "title"))]
    for docx, title in built:
        line = f"docx  {docx.relative_to(ROOT)}"
        if not args.no_pdf:
            pages = word_pass(docx, title, AUTHOR, fields="copyright" not in docx.name)
            line += f" ({pages} pages in Word)"
            if docx == manuscript and pages > MAX_PAGES:
                print(line)
                sys.exit(f"the manuscript has {pages} pages; the journal's limit is {MAX_PAGES}")
        print(line)
    return 0


