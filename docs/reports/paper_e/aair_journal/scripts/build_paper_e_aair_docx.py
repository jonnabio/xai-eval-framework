LATEX_ACCENTS = {"'": "\u0301", "`": "\u0300", "^": "\u0302", '"': "\u0308", "~": "\u0303"}


def delatex(s: str) -> str:
    s = re.sub(r"\{\\(['`^\"~])\{?([A-Za-z])\}?\}|\\(['`^\"~])\{?([A-Za-z])\}?",
               lambda m: __import__("unicodedata").normalize(
                   "NFC", (m.group(2) or m.group(4)) + LATEX_ACCENTS[m.group(1) or m.group(3)]), s)
    s = s.replace("\\&", "&").replace("~", "\u00a0").replace("--", "\u2013")
    s = s.replace("{", "").replace("}", "")
    if "\\" in s:
        sys.exit(f"LaTeX left in a reference field: {s}")
    return " ".join(s.split())


def parse_bib(text: str) -> dict[str, dict[str, str]]:
    text = re.sub(r"(?m)^%.*$", "", text)
    out = {}
    for m in re.finditer(r"@(\w+)\{([^,]+),", text):
        kind, key, i = m.group(1).lower(), m.group(2).strip(), m.end()
        depth, j = 1, i
        while depth:
            depth += {"{": 1, "}": -1}.get(text[j], 0)
            j += 1
        fields, body, k = {"type": kind}, text[i:j - 1], 0
        for f in re.finditer(r"(\w+)\s*=\s*\{", body):
            if f.start() < k:
                continue
            depth, p = 1, f.end()
            while depth:
                depth += {"{": 1, "}": -1}.get(body[p], 0)
                p += 1
            fields[f.group(1).lower()] = body[f.end():p - 1]
            k = p
        out[key] = fields
    return out


def authors(field: str) -> str:
    """"Krishna S, Han T": surname and initials, as in the template's examples."""
    names = []
    for a in field.split(" and "):
        a = delatex(a)
        last, first = (a.split(",", 1) + [""])[:2] if "," in a else (a.rsplit(" ", 1)[::-1] + [""])[:2]
        initials = "".join(p[0] for p in re.split(r"[\s.\-]+", first.strip()) if p)
        names.append(f"{last.strip()} {initials}".strip())
    return ", ".join(names)


def reference_text(key: str, e: dict[str, str]) -> str:
    """One entry in the template's form, ending in its DOI or address (LaTeX for pandoc)."""
    head = f"{authors(e['author'])}. \u201c{delatex(e['title'])}\u201d"
    year, pages = e["year"], delatex(e.get("pages", ""))
    kind = e["type"]
    if kind == "article":
        vol = e.get("volume", "") + (f"({e['number']})" if e.get("number") else "")
        where = f"{delatex(e['journal'])}" + (f" {vol}" if vol else "") + f" ({year})" + (f" {pages}" if pages else "")
    elif kind == "inproceedings":
        where = f"In: {delatex(e['booktitle'])}" + (f", vol. {e['volume']}" if e.get("volume") else "") \
                + f", ({year})" + (f" {pages}" if pages else "")
    elif kind == "book":
        where = f"{delatex(e['publisher'])}, {delatex(e['address'])}, {year}"
    else:
        where = f"{delatex(e['howpublished'])}, ({year})"
    doi = e.get("doi") or ARXIV_DOI.get(key)
    if doi:
        url = f"https://doi.org/{doi}"
        tail = f"; doi: \\href{{{url}}}{{{url}}}."
    else:
        url = re.search(r"\\fullurl\{([^}]+)\}", e.get("note", "")).group(1)
        tail = f". Available: \\href{{{url}}}{{{url}}}."
    return head + ", " + where + tail


# --- LaTeX side ---------------------------------------------------------------------

def strip_comments(tex: str) -> str:
    return re.sub(r"(?<!\\)%.*", "", tex)


def macro(tex: str, name: str) -> str:
    return " ".join(re.search(r"\\" + name + r"\{(.*?)\}\n", tex, flags=re.DOTALL).group(1).split())


def environment(tex: str, name: str) -> str:
    return " ".join(re.search(r"\\begin\{" + name + r"\}(.*?)\\end\{" + name + r"\}", tex,
                              flags=re.DOTALL).group(1).split())


def cite_text(keys: list[str], number: dict[str, int]) -> str:
    """[1], [2], [5] and [3]-[9]: separate brackets, runs of three or more as a range."""
    nums = sorted(number[k] for k in keys)
    parts, i = [], 0
    while i < len(nums):
        j = i
        while j + 1 < len(nums) and nums[j + 1] == nums[j] + 1:
            j += 1
        if j - i >= 2:
            parts.append(f"[{nums[i]}]-[{nums[j]}]")
        else:
            parts += [f"[{n}]" for n in nums[i:j + 1]]
        i = j + 1
    return ", ".join(parts)


def number_sections(body: str) -> str:
    """"1. Introduction", "1.1. Title" (template), unnumbered headings marked; \\ref resolved."""
    sec = sub = 0
    labels: dict[str, str] = {}
    current = ""
    out = []
    for piece in re.split(r"(\\(?:sub)?section\*?\{[^}]*\}|\\label\{sec:[^}]+\})", body):
        m = re.fullmatch(r"\\(section|subsection)(\*?)\{([^}]*)\}", piece)
        if m:
            kind, star, text = m.group(1), m.group(2), " ".join(m.group(3).split())
            if star:
                out.append(f"\n\nUNNUMHEAD {text}\n\n")
            elif kind == "section":
                sec, sub = sec + 1, 0
                current = str(sec)
                out.append(f"\\section*{{{sec}. {text}}}")
            else:
                sub += 1
                current = f"{sec}.{sub}"
                out.append(f"\\subsection*{{{sec}.{sub}. {text}}}")
            continue
        m = re.fullmatch(r"\\label\{(sec:[^}]+)\}", piece)
        if m:
            labels[m.group(1)] = current
            continue
        out.append(piece)
    body = "".join(out)
    return re.sub(r"\\ref\{(sec:[^}]+)\}", lambda m: labels[m.group(1)], body)


def nomenclature(body: str) -> str:
    """\\nomgroup / \\nomitem as marked paragraphs; the first group prints no label (template)."""
    first = [True]

    def group(m: re.Match) -> str:
        if first[0]:
            first[0] = False
            return "\n\n"
        return f"\n\nNOMBLANK\n\nNOMGROUP {m.group(1)}\n\n"

    body = re.sub(r"\\nomgroup\{([^}]*)\}", group, body)
    return re.sub(r"\\nomitem\{([^}]*)\}\{([^\n]*)\}", r"\n\nNOMITEM \1 NOMTAB \2\n\n", body)


def pandoc_source(tex: str, png: dict[str, Path]) -> tuple[str, list[str], int, list[float], int]:
    """The text from the Introduction on, as a small LaTeX file for pandoc.

    Returns the source, the cited keys in order, the number of numbered equations, the
    width of each figure as a share of the text width, and the number of tables.
    """
    tex = strip_comments(tex)
    body = tex[tex.index("\\section{Introduction}"):]
    body = re.sub(r"\\begin\{(table|figure)\*?\}(\[[^\]]*\])?", r"\\begin{\1}", body)
    body = re.sub(r"\\end\{(table|figure)\*\}", r"\\end{\1}", body)
    body = re.sub(r"\\renewcommand\{\\arraystretch\}\{[^}]*\}|\\setlength\{\\tabcolsep\}\{[^}]*\}"
                  r"|\\(?:small|footnotesize|centering)\b", "", body)
    order: list[str] = []
    for group in re.findall(r"\\cite\{([^}]*)\}", body):
        for k in (k.strip() for k in group.split(",")):
            if k not in order:
                order.append(k)
    number = {k: i for i, k in enumerate(order, 1)}
    body = re.sub(r"\\cite\{([^}]*)\}",
                  lambda m: cite_text([k.strip() for k in m.group(1).split(",")], number), body)
    body = number_sections(body)
    for prefix in ("tab", "fig", "eq"):
        for i, label in enumerate(re.findall(r"\\label\{(" + prefix + r":[^}]+)\}", body), 1):
            body = body.replace(f"\\ref{{{label}}}", str(i))
    equations = len(re.findall(r"\\label\{eq:", body))
    if equations != body.count("\\begin{equation}"):
        sys.exit("every displayed equation needs its label")
    body = re.sub(r"\\label\{[^}]*\}", "", body)
    if "\\ref{" in body:
        sys.exit("a \\ref is left without a number")
    # Captions end with a period; figure captions carry the template's colour note.
    body = re.sub(r"(\\begin\{figure\}.*?\\caption\{)(.*?)\}\s*\n(\s*\\end\{figure\})",
                  lambda m: m.group(1) + m.group(2).rstrip(".") + COLOR_NOTE + ".}\n" + m.group(3),
                  body, flags=re.DOTALL)
    body = re.sub(r"(\\begin\{table\}.*?\\caption\{)(.*?)\}\s*\n",
                  lambda m: m.group(1) + m.group(2).rstrip(".") + ".}\n", body, flags=re.DOTALL)
    widths = []

    def graphic(m: re.Match) -> str:
        widths.append(1.0 if m.group(1) == "\\textwidth" else 0.62)
        return "\\includegraphics{" + png[m.group(2)].name + "}"

    body = re.sub(r"\\includegraphics\[width=(\\textwidth|\\columnwidth)\]\{([^}]+)\}", graphic, body)
    body = nomenclature(body)
    tables = len(re.findall(r"\\begin\{table\}", body))
    refs = parse_bib(BIB.read_text(encoding="utf-8"))
    missing = [k for k in order if k not in refs]
    if missing:
        sys.exit(f"cited but not in references.bib: {missing}")
    body += "\n\nREFHEAD References\n\n" + "\n\n".join(
        f"REFITEM [{i}] {reference_text(k, refs[k])}" for i, k in enumerate(order, 1))
    src = ("\\documentclass{article}\n\\usepackage{amsmath,amssymb,graphicx,hyperref}\n"
           "\\begin{document}\n" + body + "\n\\end{document}\n")
    return src, order, equations, widths, tables


def figures_png(tex: str, workdir: Path) -> dict[str, Path]:
    """Each figure PDF of the CyS build (its generator: ../scripts/build_paper_e.py) at 600 dpi."""
    import pymupdf
    out = {}
    for rel in re.findall(r"\\includegraphics\[[^\]]*\]\{([^}]+\.pdf)\}", tex):
        target = workdir / (Path(rel).stem + ".png")
        page = pymupdf.open(E / rel)[0]
        page.get_pixmap(dpi=FIGURE_DPI).save(target)
        out[rel] = target
    return out


